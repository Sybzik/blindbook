export const ICON_NAMES = Object.keys(ICONS);

export function bitmapRects(rows, keyPrefix = '') {
  const out = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w++;
        out.push(<rect key={keyPrefix + x + '-' + y} x={x} y={y} width={w} height="1" />);
        x += w;
      } else x++;
    }
  });
  return out;
}

export function PixelIcon({ name, size = 14, color = 'currentColor', title, className = '', style }) {
  const rows = ICONS[name] || ICONS.warning;
  const w = rows[0].length, h = rows.length;
  return (
    <svg className={'bb-icon ' + className} width={size} height={size * h / w} viewBox={`0 0 ${w} ${h}`} fill={color}
      shapeRendering="crispEdges" role={title ? 'img' : undefined} aria-label={title} aria-hidden={title ? undefined : true}
      style={{ display: 'inline-block', flex: 'none', ...style }}>
      {bitmapRects(rows)}
    </svg>
  );
}
